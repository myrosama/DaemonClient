// Reads the compiled immich-api-shim bundle and emits it as a TS string export
// that the deployment-service worker can ship verbatim to user accounts.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const __dirname = dirname(fileURLToPath(import.meta.url));
const shimPath = resolve(__dirname, '../../user-worker/dist/index.js');
const outPath = resolve(__dirname, '../src/shim-bundle.ts');

const rawCode = readFileSync(shimPath, 'utf8');
const version = createHash('sha256').update(rawCode).digest('hex').slice(0, 12);

// Stamp the computed version into the bundle so /api/health on the deployed
// per-user worker reports the actual shim build it's running, not the static
// "1.0.0" placeholder. Lets us tell at a glance whether auto-update propagated.
const code = rawCode.replace(
  /(WORKER_VERSION\s*=\s*)(["'])[^"']*\2/,
  (_m, prefix, q) => `${prefix}${q}${version}${q}`
);

const escaped = code.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

const out = `// AUTO-GENERATED by scripts/embed-shim.mjs — do not edit by hand.
// Source: workers/user-worker/dist/index.js
export const SHIM_VERSION = ${JSON.stringify(version)};
export const SHIM_BUNDLE = \`${escaped}\`;
`;

writeFileSync(outPath, out);
console.log(`embedded shim: ${code.length} bytes → ${outPath} (version ${version})`);
